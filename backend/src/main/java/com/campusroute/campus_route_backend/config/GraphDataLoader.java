package com.campusroute.campus_route_backend.config;

import java.io.IOException;
import java.io.InputStream;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import com.campusroute.campus_route_backend.domain.Building;
import com.campusroute.campus_route_backend.domain.Edge;
import com.campusroute.campus_route_backend.domain.EdgeKind;
import com.campusroute.campus_route_backend.domain.Node;
import com.campusroute.campus_route_backend.domain.NodeType;
import com.campusroute.campus_route_backend.domain.Room;
import com.campusroute.campus_route_backend.repository.BuildingRepository;
import com.campusroute.campus_route_backend.repository.EdgeRepository;
import com.campusroute.campus_route_backend.repository.NodeRepository;
import com.campusroute.campus_route_backend.repository.RoomRepository;

import tools.jackson.databind.json.JsonMapper;

/**
 * Imports data/campus_route_graph.json at startup, only when the database is empty.
 * The JSON file is generated by tools/campus/generate.mjs: never edit it by hand.
 */
@Component
public class GraphDataLoader implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(GraphDataLoader.class);
    private static final String GRAPH_FILE = "data/campus_route_graph.json";

    // Shapes of the JSON file (only the fields we need; unknown ones are ignored)
    record GraphFile(List<BuildingJson> buildings, List<RoomJson> rooms, List<NodeJson> nodes, List<EdgeJson> edges) { }
    record BuildingJson(String code, String name, boolean outdoor, int width, int height, int[] origin,
                        String outline, String siteOutline) { }
    record RoomJson(String code, String building, int floor, String name, String type, String tag,
                    int cap, List<String> eq, int x, int y, int w, int h) { }
    record NodeJson(String id, String building, int floor, int x, int y, String type, String label) { }
    record EdgeJson(String a, String b, int w, String kind) { }

    private final BuildingRepository buildingRepository;
    private final NodeRepository nodeRepository;
    private final RoomRepository roomRepository;
    private final EdgeRepository edgeRepository;

    public GraphDataLoader(BuildingRepository buildingRepository, NodeRepository nodeRepository,
                           RoomRepository roomRepository, EdgeRepository edgeRepository) {
        this.buildingRepository = buildingRepository;
        this.nodeRepository = nodeRepository;
        this.roomRepository = roomRepository;
        this.edgeRepository = edgeRepository;
    }

    @Override
    public void run(ApplicationArguments args) throws IOException {
        load();
    }

    /** Public so tests can call it directly. Does nothing if nodes already exist. */
    @Transactional
    public void load() throws IOException {
        if (nodeRepository.count() > 0) {
            if (buildingRepository.count() == 0) {
                // Nodes without buildings: the database still holds the old one-building data
                log.warn("The database holds old data (no building). Reset it: "
                        + "\"docker compose down -v\" then \"docker compose up -d\", and restart the back-end");
            } else {
                log.info("Graph already loaded, skipping import");
            }
            return;
        }

        GraphFile graph;
        try (InputStream in = new ClassPathResource(GRAPH_FILE).getInputStream()) {
            graph = JsonMapper.builder().build().readValue(in, GraphFile.class);
        }

        // 1. buildings (plan spaces A, B, C and EXT)
        List<Building> buildings = graph.buildings().stream()
                .map(b -> new Building(b.code(), b.name(), b.outdoor(), b.width(), b.height(),
                        b.origin()[0], b.origin()[1], b.outline(), b.siteOutline()))
                .toList();
        buildingRepository.saveAll(buildings);

        // 2. nodes: rooms and edges point to them
        Map<String, Node> nodesById = new HashMap<>();
        for (NodeJson n : graph.nodes()) {
            nodesById.put(n.id(), new Node(n.id(), n.building(), n.floor(), n.x(), n.y(),
                    NodeType.valueOf(n.type().toUpperCase()), n.label()));
        }
        nodeRepository.saveAll(nodesById.values());

        // 3. rooms: a room shares its code with the node of its door
        List<Room> rooms = graph.rooms().stream()
                .map(r -> new Room(r.code(), r.building(), r.floor(), r.x(), r.y(), r.w(), r.h(),
                        r.name(), r.type(), r.tag(), r.cap(), r.eq(), nodesById.get(r.code())))
                .toList();
        roomRepository.saveAll(rooms);

        // 4. edges
        List<Edge> edges = graph.edges().stream()
                .map(e -> new Edge(nodesById.get(e.a()), nodesById.get(e.b()), e.w(),
                        EdgeKind.valueOf(e.kind().toUpperCase())))
                .toList();
        edgeRepository.saveAll(edges);

        log.info("Graph imported: {} buildings, {} rooms, {} nodes, {} edges",
                buildings.size(), rooms.size(), nodesById.size(), edges.size());
    }
}
